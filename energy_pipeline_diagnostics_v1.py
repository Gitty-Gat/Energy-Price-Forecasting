def compute_ng_ci_from_sigma2(
    forecasts: pd.DataFrame,
    sigma2: float,
    last_price: float
) -> pd.DataFrame:
    """
    Compute 95% confidence intervals for NG level forecasts assuming
    constant variance sigma2 for log returns.  This uses the property
    that the variance of the sum of independent log returns is the sum
    of their variances.  The resulting confidence interval is
    exp(cumulative mean ± 1.96 * sqrt(h * sigma2)) times the last price.

    Parameters
    ----------
    forecasts : DataFrame
        Must contain columns ['horizon', 'NG_level_forecast'] for a
        single horizon group (H) only.  The DataFrame should be in
        increasing horizon order.
    sigma2 : float
        Estimated variance of one‐step log returns from the mean model.
    last_price : float
        Last observed NG price, used to convert log returns to levels.

    Returns
    -------
    DataFrame with additional columns 'NG_lower' and 'NG_upper'.
    """
    # Compute cumulative log return from level path
    # log(path_t) = log(last_price) + cumulative log returns
    # We recover cumulative log returns as log(f_t / last_price)
    log_pred = np.log(forecasts["NG_level_forecast"] / last_price)
    horizons = forecasts["horizon"].values
    # Cumulative variance for horizon h: h * sigma2
    cum_var = horizons * sigma2
    z = 1.96
    # Lower and upper log forecasts
    log_lower = log_pred - z * np.sqrt(cum_var)
    log_upper = log_pred + z * np.sqrt(cum_var)
    forecasts = forecasts.copy()
    forecasts["NG_lower"] = last_price * np.exp(log_lower)
    forecasts["NG_upper"] = last_price * np.exp(log_upper)
    return forecasts


def visualize_forecasts(
    forecasts_file: str,
    params_ng_file: str,
    params_ol_file: str,
    results_dir: str,
    original_data: Optional[Dict[str, str]] = None,
    exog_cols: Optional[List[str]] = None,
    ng_order: Tuple[int, int, int] = (5, 0, 1),
    horizons: Optional[List[int]] = None
) -> None:
    """
    Generate and save forecast plots with confidence intervals.

    Parameters
    ----------
    forecasts_file : str
        Path to the forecasts CSV generated by the forecasting pipeline.
    params_ng_file : str
        Path to params_ng.json for NG model parameters.
    params_ol_file : str
        Path to params_ol.json for OL model parameters.
    results_dir : str
        Directory where plot images will be saved (subdir 'diagnostics').
    original_data : dict, optional
        If provided, must contain 'ng_csv', 'ol_csv', and optionally
        'exog_csv' and other keys.  When provided, the script will
        re-fit the SARIMAX mean models to compute forecast intervals
        using Statsmodels.  If None, constant variance intervals are
        used for both NG and OL.
    exog_cols : list[str], optional
        Names of exogenous columns to include when re-fitting models.
    ng_order : tuple[int, int, int]
        ARIMA order for NG mean when re-fitting.
    horizons : list[int], optional
        List of forecast horizons.  If None, unique horizons from
        forecasts_file will be used.
    """
    os.makedirs(os.path.join(results_dir, "diagnostics"), exist_ok=True)
    fc_all = pd.read_csv(forecasts_file)
    # Determine horizon groups
    if horizons is None:
        horizons = sorted(fc_all["H"].unique())
    # Load NG variance and last price
    with open(params_ng_file, "r") as f:
        params_ng = json.load(f)
    sigma2_ng = params_ng["mean"].get("sigma2")
    if sigma2_ng is None:
        sigma2_ng = params_ng["mean"].get("sigma2", 0.0)
    # Last observed price
    last_ng = float(fc_all.loc[fc_all["horizon"] == 1, "NG_level_forecast"].iloc[0])
    last_ol = float(fc_all.loc[fc_all["horizon"] == 1, "OL_level_forecast"].iloc[0])
    # Prepare plots for each horizon group separately
    for H in horizons:
        df_h = fc_all[fc_all["H"] == H].copy().sort_values("horizon")
        # Compute NG CI (constant variance assumption)
        df_ci = compute_ng_ci_from_sigma2(df_h, sigma2_ng, last_ng)
        # Plot NG path with CI
        plt.figure()
        plt.plot(df_h["date"], df_h["NG_level_forecast"], label="NG forecast")
        plt.fill_between(df_h["date"], df_ci["NG_lower"], df_ci["NG_upper"], alpha=0.2, label="95% CI")
        plt.title(f"Natural Gas Level Forecast (H={H})")
        plt.xlabel("Date")
        plt.ylabel("NG price")
        plt.legend()
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(os.path.join(results_dir, "diagnostics", f"NG_forecast_H{H}.png"))
        plt.close()
        # Oil CI
        # Try to re-fit SARIMAX for OL if original data provided
        ol_ci_lower = None
        ol_ci_upper = None
        if original_data is not None and all(k in original_data for k in ["ng_csv", "ol_csv"]):
            # Load dataset and refit SARIMAX for OL mean
            ng_df = load_price_csv(original_data["ng_csv"], "NG")
            ol_df = load_price_csv(original_data["ol_csv"], "OL")
            exog_df = load_exog_csv(original_data.get("exog_csv"))
            # If exogenous lags were provided, make lags
            if exog_df is not None:
                # Determine numeric columns in exog_df
                ex_num_cols = [c for c in exog_df.columns if c != "date" and pd.api.types.is_numeric_dtype(exog_df[c])]
                if ex_num_cols:
                    max_lag = 0
                    # derive max lag from names provided in exog_cols, e.g. HDD_l3 -> 3
                    if exog_cols:
                        for c in exog_cols:
                            if "_l" in c:
                                try:
                                    lag_val = int(c.split("_l")[-1])
                                    max_lag = max(max_lag, lag_val)
                                except Exception:
                                    pass
                    if max_lag > 0:
                        exog_df = make_lags(exog_df, ex_num_cols, max_lag=max_lag)
            df = align_calendar(ng_df, ol_df, exog_df)
            df = add_transforms(df)
            # Build exog matrix for OL
            if exog_cols:
                X_ol_full = df.set_index("date")[exog_cols].reindex(df.set_index("date").index)
            else:
                X_ol_full = None
            # Collapse returns for fitting
            y_ol_full = df.set_index("date")["dlog_OL"].dropna()
            X_ol_fit = None
            if X_ol_full is not None:
                X_ol_fit = X_ol_full.loc[y_ol_full.index]
            # Fit SARIMAX for Oil mean
            # Convert to arrays to avoid date-index warnings
            y_ol_arr = y_ol_full.to_numpy()
            X_ol_arr = None if X_ol_fit is None else X_ol_fit.to_numpy()
            try:
                res_ol = SARIMAX(y_ol_arr, order=(0, 0, 4), trend="n", exog=X_ol_arr,
                                 enforce_stationarity=False, enforce_invertibility=False
                                 ).fit(maxiter=4000, disp=False, method="powell")
            except Exception:
                res_ol = SARIMAX(y_ol_arr, order=(0, 0, 4), trend="n", exog=X_ol_arr,
                                 enforce_stationarity=False, enforce_invertibility=False
                                 ).fit(maxiter=4000, disp=False, method="lbfgs")
            # Build future exog (carry forward last values)
            if X_ol_arr is not None:
                last_row = X_ol_arr[-1]
                exog_ol_oos_arr = np.tile(last_row[None, :], (H, 1))
            else:
                exog_ol_oos_arr = None
            start_ol = len(y_ol_arr)
            end_ol = start_ol + H - 1
            ol_pred = res_ol.get_prediction(start=start_ol, end=end_ol, exog=exog_ol_oos_arr)
            pred_mean = ol_pred.predicted_mean
            conf_int = ol_pred.conf_int(alpha=0.05)
            # conf_int is shape (H, 2)
            # Build level paths
            log_pred = np.cumsum(np.asarray(pred_mean))
            log_lower = np.cumsum(conf_int[:, 0])
            log_upper = np.cumsum(conf_int[:, 1])
            ol_ci_lower = last_ol * np.exp(log_lower)
            ol_ci_upper = last_ol * np.exp(log_upper)
        # Plot OL path
        plt.figure()
        plt.plot(df_h["date"], df_h["OL_level_forecast"], label="OL forecast")
        if ol_ci_lower is not None and ol_ci_upper is not None:
            plt.fill_between(df_h["date"], ol_ci_lower, ol_ci_upper, alpha=0.2, label="95% CI")
        else:
            # constant variance using sigma2 from params_ol
            with open(params_ol_file, "r") as f:
                params_ol = json.load(f)
            sigma2_ol = params_ol.get("arimax", {}).get("sigma2")
            if sigma2_ol is None:
                sigma2_ol = params_ol.get("arimax", {}).get("sigma2", 0.0)
            # compute CI similar to NG constant variance
            log_pred = np.log(df_h["OL_level_forecast"] / last_ol)
            horizons_vec = df_h["horizon"].values
            cum_var = horizons_vec * sigma2_ol
            z = 1.96
            log_lower = log_pred - z * np.sqrt(cum_var)
            log_upper = log_pred + z * np.sqrt(cum_var)
            lower_path = last_ol * np.exp(log_lower)
            upper_path = last_ol * np.exp(log_upper)
            plt.fill_between(df_h["date"], lower_path, upper_path, alpha=0.2, label="95% CI")
        plt.title(f"Crude Oil Level Forecast (H={H})")
        plt.xlabel("Date")
        plt.ylabel("Oil price")
        plt.legend()
        plt.xticks(rotation=45)
        plt.tight_layout()
        plt.savefig(os.path.join(results_dir, "diagnostics", f"OL_forecast_H{H}.png"))
        plt.close()


