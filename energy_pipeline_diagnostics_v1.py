def compute_performance_metrics(
    python_forecasts: pd.DataFrame,
    r_forecasts: pd.DataFrame
) -> Dict[str, Dict[str, float]]:
    """
    Compute RMSE and MAE between Python and R forecasts for NG and OL level
    forecasts.  Both DataFrames must have columns ['date','horizon',
    'NG_level_forecast','OL_level_forecast'] and cover the same dates and
    horizons.  The function groups by horizon and computes metrics for each
    series separately.
    Returns a dictionary keyed by horizon and series.
    """
    metrics = {}
    # Merge on date and horizon
    merged = pd.merge(
        python_forecasts,
        r_forecasts,
        on=["date", "horizon"],
        suffixes=("_py", "_r"),
        how="inner"
    )
    if merged.empty:
        raise ValueError("No overlapping forecasts between Python and R results.")
    for H in sorted(merged["horizon"].unique()):
        df_h = merged[merged["horizon"] == H]
        err_ng = df_h["NG_level_forecast_py"] - df_h["NG_level_forecast_r"]
        err_ol = df_h["OL_level_forecast_py"] - df_h["OL_level_forecast_r"]
        rmse_ng = float(np.sqrt(np.mean(err_ng ** 2)))
        rmse_ol = float(np.sqrt(np.mean(err_ol ** 2)))
        mae_ng = float(np.mean(np.abs(err_ng)))
        mae_ol = float(np.mean(np.abs(err_ol)))
        metrics[f"H={H}"] = {
            "NG_RMSE": rmse_ng,
            "NG_MAE": mae_ng,
            "OL_RMSE": rmse_ol,
            "OL_MAE": mae_ol,
        }
    return metrics


