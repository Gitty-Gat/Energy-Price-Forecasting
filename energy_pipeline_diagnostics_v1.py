def main() -> None:
    parser = argparse.ArgumentParser(
        description="Diagnostics and visualization for NG/OL forecasting pipeline."
    )
    parser.add_argument("--results_dir", type=str, required=True,
                        help="Directory containing pipeline outputs (forecasts_levels.csv, params_*.json).")
    parser.add_argument("--ng_csv", type=str, default=None,
                        help="Path to NG price CSV for refitting models (optional).")
    parser.add_argument("--ol_csv", type=str, default=None,
                        help="Path to OL price CSV for refitting models (optional).")
    parser.add_argument("--exog_csv", type=str, default=None,
                        help="Path to exogenous regressors CSV for refitting models (optional).")
    parser.add_argument("--agg_level", type=str, default="none",
                        choices=["none", "national", "division"],
                        help="Aggregation level for exogenous data (unused here).")
    parser.add_argument("--exog_cols", type=str, nargs="*", default=None,
                        help="Names of exogenous columns to include after lagging.")
    parser.add_argument("--ng_order", type=int, nargs=3, default=[5, 0, 1],
                        help="ARIMA order for NG mean model.")
    parser.add_argument("--horizons", type=int, nargs="*", default=None,
                        help="List of forecast horizons to process.  If omitted, uses unique horizons from forecasts file.")
    parser.add_argument("--r_results_csv", type=str, default=None,
                        help="Path to R-generated forecast CSV for performance validation (optional).")
    parser.add_argument("--r_ng_csv", type=str, default=None,
                    help="Path to R NG forecast CSV (e.g., ng_forecasts_scenario.csv)")
    parser.add_argument("--r_ol_csv", type=str, default=None,
                    help="Path to R Oil forecast CSV (e.g., oil_forecasts_scenario.csv)")

    args = parser.parse_args()
    # Locate files in results_dir
    forecasts_file = os.path.join(args.results_dir, "forecasts_levels.csv")
    params_ng_file = os.path.join(args.results_dir, "params_ng.json")
    params_ol_file = os.path.join(args.results_dir, "params_ol.json")
    if not os.path.isfile(forecasts_file):
        raise FileNotFoundError(f"Forecasts file not found: {forecasts_file}")
    if not os.path.isfile(params_ng_file):
        raise FileNotFoundError(f"params_ng.json not found in {args.results_dir}")
    if not os.path.isfile(params_ol_file):
        raise FileNotFoundError(f"params_ol.json not found in {args.results_dir}")
    # Step 1: Forecast visualization
    original_data = None
    if args.ng_csv and args.ol_csv:
        original_data = {
            "ng_csv": args.ng_csv,
            "ol_csv": args.ol_csv,
            "exog_csv": args.exog_csv,
        }
    visualize_forecasts(
        forecasts_file,
        params_ng_file,
        params_ol_file,
        args.results_dir,
        original_data=original_data,
        exog_cols=args.exog_cols,
        ng_order=tuple(args.ng_order),
        horizons=args.horizons
    )
    # Step 2: Residual diagnostics (if original data provided)
    if original_data is not None:
        # Load and prepare full dataframe for diagnostics
        ng_df = load_price_csv(args.ng_csv, "NG")
        ol_df = load_price_csv(args.ol_csv, "OL")
        exog_df = load_exog_csv(args.exog_csv)
        # Determine maximum lag for exogenous columns
        if exog_df is not None and args.exog_cols:
            ex_num_cols = [c for c in exog_df.columns if c != "date" and pd.api.types.is_numeric_dtype(exog_df[c])]
            max_lag = 0
            for c in args.exog_cols:
                if "_l" in c:
                    try:
                        lag_val = int(c.split("_l")[-1])
                        max_lag = max(max_lag, lag_val)
                    except Exception:
                        pass
            if max_lag > 0 and ex_num_cols:
                exog_df = make_lags(exog_df, ex_num_cols, max_lag=max_lag)
        df = align_calendar(ng_df, ol_df, exog_df)
        df = add_transforms(df)
        diagnostics = compute_residual_diagnostics(
            df,
            args.exog_cols,
            tuple(args.ng_order),
            args.horizons or sorted(pd.read_csv(forecasts_file)["H"].unique()),
            args.results_dir
        )
        print("Residual diagnostics:")
        for series, stats in diagnostics.items():
            print(series, stats)
    # Step 3: Performance validation (optional)
    if args.r_results_csv:
        py_fc = pd.read_csv(forecasts_file)
        r_fc = pd.read_csv(args.r_results_csv)
        metrics = compute_performance_metrics(py_fc, r_fc)
        print("Performance validation (Python vs R):")
        for h, m in metrics.items():
            print(h, m)
        # Save metrics JSON
        with open(os.path.join(args.results_dir, "diagnostics", "performance_metrics.json"), "w") as f:
            json.dump(metrics, f, indent=2)


if __name__ == "__main__":
    main()