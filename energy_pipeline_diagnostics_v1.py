def read_table_any(path: str) -> pd.DataFrame:
    """Read a CSV/TSV file, sniffing delimiters automatically."""
    return pd.read_csv(path, sep=None, engine="python")


def _infer_columns(df: pd.DataFrame) -> Tuple[str, str]:
    """Infer date and price columns from a price CSV."""
    date_candidates = ["date", "Date", "DATE", "timestamp", "Timestamp"]
    price_candidates = [
        "PRICE_NG", "PRICE_OL", "price", "Price",
        "settle", "Settle", "PX_LAST"
    ]
    dcol = next((c for c in date_candidates if c in df.columns), None)
    if dcol is None:
        # fallback: try any column convertible to datetime
        for c in df.columns:
            try:
                pd.to_datetime(df[c])
                dcol = c
                break
            except Exception:
                continue
    if dcol is None:
        raise ValueError("Could not infer a date column in price CSV.")
    pcol = next((c for c in price_candidates if c in df.columns), None)
    if pcol is None:
        # fallback: first numeric column not date
        for c in df.columns:
            if c == dcol:
                continue
            if pd.api.types.is_numeric_dtype(df[c]):
                pcol = c
                break
    if pcol is None:
        raise ValueError("Could not infer a price column in price CSV.")
    return dcol, pcol

