#!/usr/bin/env python3
"""
energy_pipeline_diagnostics_v1.py
=================================

This companion script provides diagnostic and visualization utilities for the
natural gas and oil forecasting pipeline.  It is designed to operate on
outputs produced by the ``energy_pipeline_forecast_v1.2.py`` script and to
recompute residual diagnostics when provided with the original data sources.

The script implements three key functions:

1. **Forecast Visualization**
   - Reads the ``forecasts_levels.csv`` file generated by the forecasting
     pipeline.
   - For natural gas (NG), computes a constant‐variance 95 % confidence
     interval based on the estimated variance of the ARIMAX mean model.
     This approximation yields fan charts around the forecast path.
   - For crude oil (OL), optionally refits a SARIMAX model on the provided
     data to obtain prediction intervals via Statsmodels.  If the original
     data are not provided, the script falls back to constant variance as
     well.
   - Generates separate matplotlib charts for NG and OL, saving them in
     ``<results_dir>/diagnostics``.

2. **Residual Diagnostics**
   - If the original series and exogenous regressors are supplied, the
     script reloads the data, reconstructs the ARIMAX models and the GARCH
     volatility model for NG, and computes standardized residuals.
   - Computes Ljung–Box and ARCH LM p‐values for both series to assess
     autocorrelation and remaining heteroskedasticity.
   - Performs the Jarque–Bera normality test on standardized residuals.
   - Plots ACF and PACF of the standardized residuals (one chart per
     series).  Each plot is saved in ``<results_dir>/diagnostics``.

3. **Performance Validation**
   - When provided with an external benchmark CSV (e.g. forecasts produced
     from an R workflow), computes RMSE and MAE for NG and OL level
     forecasts against the Python forecasts.
   - Optionally, the script can be extended to compute Diebold–Mariano
     statistics for comparative forecasting accuracy.

Usage example:

    python energy_pipeline_diagnostics_v1.py \
        --results_dir /path/to/Python\ Model\ Outputs \
        --ng_csv /path/to/NG_prompt_month_futures_price.csv \
        --ol_csv /path/to/Oil_prompt_month_futures_price.csv \
        --exog_csv /path/to/weather_lagged.csv \
        --agg_level none \
        --exog_cols HDD CDD HDD_l1 HDD_l2 HDD_l3 CDD_l1 CDD_l2 CDD_l3 HDD_3dma CDD_3dma \
        --ng_order 5 0 1 \
        --r_results_csv /path/to/R_forecasts.csv

The script is intended to be modular; if no original data are provided, it
will still produce forecast plots using constant variance approximations.

"""

