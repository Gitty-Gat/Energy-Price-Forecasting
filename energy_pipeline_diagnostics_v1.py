def compute_residual_diagnostics(
    df: pd.DataFrame,
    exog_cols: Optional[List[str]],
    ng_order: Tuple[int, int, int],
    horizons: List[int],
    results_dir: str
) -> Dict[str, Dict[str, float]]:
    """
    Compute and save residual diagnostics for NG and OL.

    Fits ARIMAX and GARCH models using the supplied DataFrame
    (must include columns date, dlog_NG, dlog_OL, plus exogenous variables).

    Returns a dictionary with Ljung–Box and ARCH LM p-values and Jarque–Bera
    statistics for each series.
    """
    diagnostics = {}
    # Fit NG mean model (ARIMAX) and volatility model if possible
    # Build exog matrix for NG
    y_ng = df.set_index("date")["dlog_NG"].dropna()
    X_ng = None
    if exog_cols:
        X_ng_full = df.set_index("date")[exog_cols]
        X_ng = X_ng_full.loc[y_ng.index]
    # Fit SARIMAX mean
    p, d, q = ng_order
    y_ng_arr = y_ng.to_numpy()
    X_ng_arr = None if X_ng is None else X_ng.to_numpy()
    try:
        res_ng = SARIMAX(
            y_ng_arr, order=(p, d, q), trend="n",
            exog=X_ng_arr, enforce_stationarity=False, enforce_invertibility=False
        ).fit(maxiter=4000, disp=False, method="powell")
    except Exception:
        res_ng = SARIMAX(
            y_ng_arr, order=(p, d, q), trend="n",
            exog=X_ng_arr, enforce_stationarity=False, enforce_invertibility=False
        ).fit(maxiter=4000, disp=False, method="lbfgs")
    resid_ng = pd.Series(res_ng.resid, index=y_ng.index).dropna()
    # Fit GARCH on residuals (if possible)
    if HAVE_ARCH:
        try:
            # Student t distribution by default
            # Scale residuals by 100 to improve numerical stability
            scale = 100.0
            am = arch_model(resid_ng.values * scale, p=1, o=0, q=1, mean="zero", vol="Garch", dist="t")
            gfit = am.fit(update_freq=0, disp="off", show_warning=False, options={"maxiter": 4000})
            # Standardised residuals on original scale
            cond_vol = gfit.conditional_volatility / scale
            std_resid = (resid_ng / cond_vol)
        except Exception:
            std_resid = resid_ng / np.std(resid_ng.dropna())
    else:
        std_resid = resid_ng / np.std(resid_ng.dropna())
    # Diagnostics for NG
    lb_ng = acorr_ljungbox(std_resid.dropna(), lags=[20], return_df=True)
    lb_p_ng = float(lb_ng["lb_pvalue"].iloc[0])
    try:
        lm_stat_ng, lm_p_ng, _, _ = het_arch(std_resid.dropna(), nlags=20)
        arch_p_ng = float(lm_p_ng)
    except Exception:
        arch_p_ng = float("nan")
    jb_stat_ng, jb_p_ng, _, _ = jarque_bera(std_resid.dropna())
    # Plot ACF/PACF for NG residuals
    from statsmodels.graphics.tsaplots import plot_acf, plot_pacf
    plt.figure()
    plot_acf(std_resid.dropna(), lags=20)
    plt.title("ACF of NG standardized residuals")
    plt.tight_layout()
    plt.savefig(os.path.join(results_dir, "diagnostics", "NG_resid_acf.png"))
    plt.close()
    plt.figure()
    plot_pacf(std_resid.dropna(), lags=20, method="ywm")
    plt.title("PACF of NG standardized residuals")
    plt.tight_layout()
    plt.savefig(os.path.join(results_dir, "diagnostics", "NG_resid_pacf.png"))
    plt.close()
    diagnostics["NG"] = {
        "ljungbox_p": lb_p_ng,
        "arch_lm_p": arch_p_ng,
        "jarque_bera_p": float(jb_p_ng)
    }
    # Fit OL mean model (ARIMAX(0,0,4))
    y_ol = df.set_index("date")["dlog_OL"].dropna()
    X_ol = None
    if exog_cols:
        X_ol_full = df.set_index("date")[exog_cols]
        X_ol = X_ol_full.loc[y_ol.index]
    y_ol_arr = y_ol.to_numpy()
    X_ol_arr = None if X_ol is None else X_ol.to_numpy()
    try:
        res_ol = SARIMAX(
            y_ol_arr, order=(0, 0, 4), trend="n",
            exog=X_ol_arr, enforce_stationarity=False, enforce_invertibility=False
        ).fit(maxiter=4000, disp=False, method="powell")
    except Exception:
        res_ol = SARIMAX(
            y_ol_arr, order=(0, 0, 4), trend="n",
            exog=X_ol_arr, enforce_stationarity=False, enforce_invertibility=False
        ).fit(maxiter=4000, disp=False, method="lbfgs")
    resid_ol = pd.Series(res_ol.resid, index=y_ol.index).dropna()
    std_resid_ol = resid_ol / np.std(resid_ol.dropna())
    lb_ol = acorr_ljungbox(std_resid_ol.dropna(), lags=[20], return_df=True)
    lb_p_ol = float(lb_ol["lb_pvalue"].iloc[0])
    try:
        lm_stat_ol, lm_p_ol, _, _ = het_arch(std_resid_ol.dropna(), nlags=20)
        arch_p_ol = float(lm_p_ol)
    except Exception:
        arch_p_ol = float("nan")
    jb_stat_ol, jb_p_ol, _, _ = jarque_bera(std_resid_ol.dropna())
    # Plot ACF/PACF for OL residuals
    plt.figure()
    plot_acf(std_resid_ol.dropna(), lags=20)
    plt.title("ACF of OL standardized residuals")
    plt.tight_layout()
    plt.savefig(os.path.join(results_dir, "diagnostics", "OL_resid_acf.png"))
    plt.close()
    plt.figure()
    plot_pacf(std_resid_ol.dropna(), lags=20, method="ywm")
    plt.title("PACF of OL standardized residuals")
    plt.tight_layout()
    plt.savefig(os.path.join(results_dir, "diagnostics", "OL_resid_pacf.png"))
    plt.close()
    diagnostics["OL"] = {
        "ljungbox_p": lb_p_ol,
        "arch_lm_p": arch_p_ol,
        "jarque_bera_p": float(jb_p_ol)
    }
    # Save diagnostics summary JSON
    with open(os.path.join(results_dir, "diagnostics", "residual_diagnostics.json"), "w") as f:
        json.dump(diagnostics, f, indent=2)
    return diagnostics


