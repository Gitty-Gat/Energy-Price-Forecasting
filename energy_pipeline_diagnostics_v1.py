def _load_r_fc(path: str, commodity: str) -> pd.DataFrame:
    """
    Load an R forecast CSV with flexible column names.
    Required info: date, horizon, level (forecasted level price).
    Optional: scenario column.
    """
    if path is None:
        return pd.DataFrame()
    df = pd.read_csv(path)
    cols = {c.lower(): c for c in df.columns}

    # Try to find columns
    date_col = cols.get("date") or cols.get("ds") or cols.get("time") or list(df.columns)[0]
    hor_col  = cols.get("horizon") or cols.get("h") or "horizon"
    lvl_col  = cols.get("level") or cols.get("forecast") or cols.get("yhat") or "level"
    scen_col = cols.get("scenario")  # optional

    # Normalize
    out = pd.DataFrame({
        "date": pd.to_datetime(df[date_col]),
        "horizon": df[hor_col].astype(int) if hor_col in df else np.arange(1, len(df)+1),
        "level": pd.to_numeric(df[lvl_col], errors="coerce")
    })
    out["commodity"] = commodity
    if scen_col:
        out["scenario"] = df[scen_col].astype(str)
    else:
        out["scenario"] = "R_default"
    return out.dropna(subset=["date", "horizon", "level"])


